//switch

let n = 2;


switch(n){
    case 1 ://1 says n value:
        console.log("ONE");
        break;
    case "2":
        console.log("TWO");
        break;
    case 3:
        console.log("Three");
        break;
    case 4:
        console.log("Four");
        break;

    default:
        console.log("More than 10");
}
